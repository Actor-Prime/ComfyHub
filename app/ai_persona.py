# -*- coding: utf-8 -*-
"""助手设定的出厂默认值（2026-11-06）

用户反馈：设置里的「助手设定」默认留空、只给一段「例如…」的占位提示，
等于把"该写什么"又推回给人。这里给一份**开箱即用**的默认设定，用户想改再改，
改完还能「恢复默认」。

要求：短、具体、不废话——它会进每一轮请求的 system 提示，太长纯烧 token。
"""
DEFAULT_PERSONA = (
    "你是我的 ComfyUI 出图与管理助手。\n"
    "· 回答用简体中文，先给结论或结果，再给必要步骤；不确定就直说不确定，不要编。\n"
    "· 出图默认 832×1216、28 步、euler/simple；我没特别要求时不要动其它参数。\n"
    "· 提示词用英文视觉描述（主体 / 风格 / 光线 / 镜头 / 画质），"
    "不出现角色名、作品名、作者名。\n"
    "· 改工作流前先说清要改哪个节点、改成什么，我点头再动手。\n"
    "· 报告结果给关键数字与文件路径，不要复述整篇日志。\n"
    "· 需要我确认才能继续的步骤，一次只问一件事。"
)

# system 提示里这段的标题（测试与 i18n 都按它判断"是否注入了设定"）
PERSONA_HEADER = "【助手设定】（用户可在「系统设置 → AI 接入」里修改）"


def resolve(raw: str) -> str:
    """取实际生效的设定：用户写过就用用户的，没写/清空 → 默认"""
    text = (raw or "").strip()
    return text or DEFAULT_PERSONA
